/**
 * Which drawing (shape) and colours each plant gets in PlantArt. Pure data so scripts can check it
 * against the plant database. Plants not listed fall back to a shape for their kind.
 */
export type ArtShape =
  | 'round' | 'pear' | 'lemon' | 'berries' | 'cluster' | 'cherries' | 'strawberry' | 'bramble'
  | 'bell' | 'chili' | 'carrot' | 'roundroot' | 'tuber' | 'bulb' | 'garlic' | 'stalk'
  | 'leafy' | 'cabbage' | 'broccoli' | 'pod' | 'long' | 'pumpkin' | 'melon' | 'corn' | 'grain'
  | 'herb' | 'lavender' | 'nut' | 'peanut' | 'flower' | 'clover' | 'tree';

/** main: body colour; alt: a second colour (stem, top, stripes, flower centre) where the shape uses one. */
/** leaf: herb leaf style (broad: basil, mint; feather: dill; needle: rosemary; frilly: parsley). */
export interface ArtSpec { shape: ArtShape; main: string; alt?: string; calyx?: boolean; leaf?: 'broad' | 'feather' | 'needle' | 'frilly' }

